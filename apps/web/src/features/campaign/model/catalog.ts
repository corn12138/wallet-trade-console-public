// A new template must not render raw message keys when an older catalog is active.
export function campaignCatalogReady(messages: Record<string, unknown>): boolean {
  const catalog = messages.campaignV2;
  return !!catalog && typeof catalog === "object" && requiredKeys.every((key) => typeof (catalog as Record<string, unknown>)[key] === "string");
}
